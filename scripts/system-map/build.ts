/**
 * Build data/system-map/model.json from the verified claims, factors.json, narrators.json and
 * overrides.json (applied last). Re-runnable: hand edits live in factors.json and overrides.json,
 * never in model.json.
 *
 *   yarn system-map:build
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadNarrators, loadRecording } from '../lib/narratives/transcripts';
import { DATA_DIR } from './paths';
import { buildClaims, buildEdges, factorResolver, findContradictions, resolveFactors } from '@/lib/system-map/model';
import type { FactorDef, NarratorInfo, Overrides, RawClaim } from '@/lib/system-map/model';

const read = <T>(file: string): T => JSON.parse(readFileSync(join(DATA_DIR, file), 'utf-8'));

function main() {
  const factorDefs = read<{ columns: string[]; factors: FactorDef[] }>('factors.json').factors;
  const overrides = read<Overrides>('overrides.json');
  const resolve = factorResolver(factorDefs, overrides);
  const factors = resolveFactors(factorDefs, overrides);
  const known = new Set(factors.map((f) => f.name));

  const narrators = loadNarrators().map((n) => {
    const recordings = n.recordings.map((r) => {
      const rec = loadRecording(n.slug, r.part, r.story_id);
      return { part: r.part, storyId: r.story_id, storyUuid: rec.storyUuid, title: rec.title };
    });
    const info: NarratorInfo & Record<string, unknown> = {
      slug: n.slug,
      name: n.name,
      regions: (n as any).regions ?? [],
      cohort: (n as any).cohort ?? 'unknown',
      joined: (n as any).joined ?? null,
      recordings,
    };
    return info;
  });
  const byNarrator = new Map(narrators.map((n) => [n.slug, n]));

  const claims = narrators.flatMap((n) => {
    const raw = read<{ claims: RawClaim[] }>(join('claims', `${n.slug}.json`)).claims;
    return buildClaims(n, raw, resolve, overrides);
  });

  const unknown = [...new Set(claims.flatMap((c) => [c.from, c.to]).filter((f) => !known.has(f)))];
  if (unknown.length) {
    console.error(`Factors not in factors.json (add them or alias them): ${unknown.join(', ')}`);
    process.exit(1);
  }
  const unmatchedOverrides = Object.keys(overrides.claims ?? {}).filter((id) => !claims.some((c) => c.id === id));
  if (unmatchedOverrides.length)
    console.warn(`Overrides for claims that no longer exist: ${unmatchedOverrides.join(', ')}`);

  const edges = buildEdges(claims, byNarrator);
  const contradictions = findContradictions(edges, factors);

  const used = new Set(claims.filter((c) => c.review_status !== 'hidden').flatMap((c) => [c.from, c.to]));
  const model = {
    _comment:
      'Generated by scripts/system-map/build.ts. Do not edit; edit factors.json, narrators.json or overrides.json and rebuild.',
    generated_at: new Date().toISOString(),
    columns: ['pressure', 'structure', 'people', 'outcome'],
    narrators,
    factors: factors
      .filter((f) => used.has(f.name))
      .map((f) => ({
        name: f.name,
        column: f.column,
        definition: f.definition,
        valence: f.valence,
        claimCount: claims.filter((c) => c.review_status !== 'hidden' && (c.from === f.name || c.to === f.name)).length,
      })),
    claims,
    edges,
    contradictions,
  };
  writeFileSync(join(DATA_DIR, 'model.json'), `${JSON.stringify(model, null, 1)}\n`);
  console.log(
    `model.json: ${narrators.length} narrators, ${model.factors.length} factors, ${claims.length} claims, ` +
      `${edges.length} edges, ${contradictions.length} contradictions`,
  );
}

main();
