/**
 * Build data/journeys-canon/model.json from the verified extractions, events.json, data/narrators.json
 * and overrides.json (applied last). Re-runnable: hand edits live in events.json and overrides.json.
 *
 *   yarn journeys:build
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildModel } from '@/lib/journeys-canon/model';
import type { EventDef, NarratorMeta, Overrides, RawNarrator } from '@/lib/journeys-canon/model';
import { loadNarrators, loadRecording } from '../lib/narratives/transcripts';
import { DATA_DIR } from './paths';

const read = <T>(file: string): T => JSON.parse(readFileSync(join(DATA_DIR, file), 'utf-8'));

function main() {
  const registry = loadNarrators();
  const metas: NarratorMeta[] = registry.map((n) => ({
    slug: n.slug,
    name: n.name,
    regions: (n as any).regions ?? [],
    cohort: (n as any).cohort ?? 'unknown',
    recordings: n.recordings.map((r) => {
      const rec = loadRecording(n.slug, r.part, r.story_id);
      return {
        part: r.part,
        storyUuid: rec.storyUuid,
        recordYear: rec.recordDate ? Number(rec.recordDate.slice(0, 4)) : null,
      };
    }),
  }));
  const raw = registry.map((n) => read<RawNarrator>(join('extracted', `${n.slug}.json`)));
  const eventsDoc = read<{ bands: string[] | null; events: EventDef[] }>('events.json');
  const overrides = read<Overrides>('overrides.json');

  const model = buildModel(metas, raw, eventsDoc.events, overrides, eventsDoc.bands);

  const ids = new Set([
    ...model.moments.map((m) => m.id),
    ...model.mentions.map((m) => m.id),
    ...model.stories.map((s) => s.id),
    ...model.questions.map((q) => q.id),
  ]);
  const stale = [
    ...Object.keys(overrides.moments ?? {}),
    ...Object.keys(overrides.eventMentions ?? {}),
    ...Object.keys(overrides.stories ?? {}),
    ...Object.keys(overrides.questions ?? {}),
  ].filter((id) => !ids.has(id));
  if (stale.length) console.warn(`Overrides for items that no longer exist: ${stale.join(', ')}`);

  writeFileSync(
    join(DATA_DIR, 'model.json'),
    `${JSON.stringify({ _comment: 'Generated by scripts/journeys-canon/build.ts. Do not edit; edit events.json or overrides.json and rebuild.', generated_at: new Date().toISOString(), ...model }, null, 1)}\n`,
  );
  const shared = model.events.filter((e) => e.narrators.length >= 2);
  console.log(
    `model.json: ${model.narrators.length} narrators, ${model.moments.length} moments, ${model.events.length} events ` +
      `(${shared.length} shared), ${model.stories.length} stories, ${model.questions.length} questions, ${model.bands.length} bands`,
  );
}

main();
